"""Exact symmetries of the polynomial problem max D over the product of spheres.

Two kinds are used. Signed coordinate permutations of determinant one leave every
determinant unchanged, since det(QP) = det Q det P. Vertex relabelings that map the
facet set of the type onto itself leave D unchanged when they preserve orientation,
and send D to -D otherwise; pairing the latter with a reflection gives an invariance
again. Every generator is checked against D before use.
"""

from __future__ import annotations

from dataclasses import dataclass
from math import factorial

from ..certify import Monomial, Polynomial, SignedVolume
from ..combinatorics import OrientedComplex
from ..combinatorics.complex import permutation_parity


@dataclass(frozen=True)
class Symmetry:
    """Substitution x[v, k] -> signs[k] * x[vertices[v], coords[k]] on flattened coordinates."""

    vertices: tuple[int, ...]
    coords: tuple[int, ...]
    signs: tuple[int, ...]

    @classmethod
    def identity(cls, n: int, d: int) -> Symmetry:
        """The trivial substitution."""
        return cls(tuple(range(n)), tuple(range(d)), (1,) * d)

    def compose(self, other: Symmetry) -> Symmetry:
        """The substitution ``self`` applied after ``other``."""
        return Symmetry(
            vertices=tuple(self.vertices[v] for v in other.vertices),
            coords=tuple(self.coords[k] for k in other.coords),
            signs=tuple(s * self.signs[k] for s, k in zip(other.signs, other.coords)),
        )

    def apply(self, monomial: Monomial, d: int) -> tuple[Monomial, int]:
        """Image of a monomial as (sorted monomial, sign)."""
        sign, image = 1, []
        for var in monomial:
            v, k = divmod(var, d)
            sign *= self.signs[k]
            image.append(d * self.vertices[v] + self.coords[k])
        return tuple(sorted(image)), sign

    def acts_on(self, polynomial: Polynomial, d: int) -> Polynomial:
        """The image of a polynomial under the substitution."""
        return polynomial.substitute(
            {m: (sign, image) for m, (image, sign) in
             ((m, self.apply(m, d)) for m in polynomial.terms)})


def closure(generators: list[Symmetry], identity: Symmetry) -> set[Symmetry]:
    """Every element of the group generated by ``generators``."""
    group, frontier = {identity}, [identity]
    while frontier:
        fresh = []
        for g in frontier:
            for h in generators:
                gh = h.compose(g)
                if gh not in group:
                    group.add(gh)
                    fresh.append(gh)
        frontier = fresh
    return group


def generating_subset(elements: list[Symmetry], identity: Symmetry) -> list[Symmetry]:
    """A small subset of ``elements`` generating the same group."""
    generators: list[Symmetry] = []
    group = {identity}
    for g in elements:
        if g not in group:
            generators.append(g)
            group = closure(generators, identity)
    return generators


class TypeAutomorphisms:
    """Vertex permutations mapping the facet set of an oriented type onto itself."""

    def __init__(self, cx: OrientedComplex):
        self.cx = cx
        self.facets = {frozenset(f): f for f in cx.facets}
        self.degree = cx.degrees()
        self.star = {v: [frozenset(f) for f in cx.star(v)] for v in range(cx.n)}

    def find(self) -> list[tuple[tuple[int, ...], int]]:
        """All automorphisms as (vertex permutation, orientation sign)."""
        n = self.cx.n
        found: list[tuple[tuple[int, ...], int]] = []
        mapping: dict[int, int] = {}

        def extend(v: int) -> None:
            if v == n:
                perm = tuple(mapping[u] for u in range(n))
                found.append((perm, self._orientation(perm)))
                return
            for w in range(n):
                if w in mapping.values() or self.degree[w] != self.degree[v]:
                    continue
                mapping[v] = w
                if self._consistent(v, mapping):
                    extend(v + 1)
                del mapping[v]

        extend(0)
        return found

    def _consistent(self, v: int, mapping: dict[int, int]) -> bool:
        """Whether every fully mapped facet through ``v`` lands on a facet."""
        return all(
            frozenset(mapping[u] for u in f) in self.facets
            for f in self.star[v]
            if all(u in mapping for u in f)
        )

    def _orientation(self, perm: tuple[int, ...]) -> int:
        """+1 if the relabeling preserves facet orientation, -1 if it reverses it."""
        signs = set()
        for f in self.cx.facets:
            image = tuple(perm[u] for u in f)
            target = self.facets[frozenset(image)]
            signs.add(permutation_parity(tuple(target.index(u) for u in image)))
        if len(signs) != 1:
            raise RuntimeError(f"automorphism {perm} is not coherently oriented")
        return signs.pop()


class SymmetryGroup:
    """Exact symmetries of max D over the product of spheres for one type."""

    def __init__(self, cx: OrientedComplex, *, use_type_automorphisms: bool = True):
        self.cx = cx
        self.identity = Symmetry.identity(cx.n, cx.d)
        self.automorphisms = TypeAutomorphisms(cx).find() if use_type_automorphisms else []
        self.generators = self._coordinate_generators() + self._type_generators()

    def _reflection(self) -> tuple[int, ...]:
        """Signs of the reflection negating the first coordinate."""
        return tuple(-1 if k == 0 else 1 for k in range(self.cx.d))

    def _coordinate_generators(self) -> list[Symmetry]:
        """Signed coordinate permutations of determinant one, acting on every vertex alike."""
        d = self.cx.d
        generators = []
        for k in range(d - 1):
            swap = list(range(d))
            swap[k], swap[k + 1] = swap[k + 1], swap[k]
            generators.append(Symmetry(self.identity.vertices, tuple(swap), self._reflection()))
        double = tuple(-1 if k < 2 else 1 for k in range(d))
        generators.append(Symmetry(self.identity.vertices, self.identity.coords, double))
        if len(closure(generators, self.identity)) != factorial(d) * 2 ** (d - 1):
            raise RuntimeError("coordinate generators do not generate the rotation subgroup")
        return generators

    def _type_generators(self) -> list[Symmetry]:
        """Facet-preserving relabelings, with a reflection when they reverse orientation."""
        elements = [
            Symmetry(perm, self.identity.coords,
                     self.identity.signs if orientation > 0 else self._reflection())
            for perm, orientation in self.automorphisms
        ]
        return generating_subset(elements, self.identity)

    def order(self) -> int:
        """Size of the generated group."""
        return len(closure(self.generators, self.identity))

    def check_invariance(self, polynomial: Polynomial) -> None:
        """Raise unless every generator leaves the polynomial exactly unchanged."""
        for g in self.generators:
            if g.acts_on(polynomial, self.cx.d) != polynomial:
                raise RuntimeError(f"{g} is not a symmetry of the polynomial")

    @classmethod
    def for_signed_volume(cls, cx: OrientedComplex,
                          *, use_type_automorphisms: bool = True) -> SymmetryGroup:
        """The group of the signed volume of ``cx``, with invariance checked."""
        group = cls(cx, use_type_automorphisms=use_type_automorphisms)
        group.check_invariance(SignedVolume(cx).polynomial)
        return group
